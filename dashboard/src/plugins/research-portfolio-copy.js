  function text(language = "en", key = "") {
    const normalized = catalog[language] ? language : "en";
    return catalog[normalized]?.[key] || catalog.en?.[key] || "";
  }

  // Fill {name} placeholders the way a template literal would (String(value), so undefined prints as such).
  function format(language = "en", key = "", params = {}) {
    return text(language, key).replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  }

