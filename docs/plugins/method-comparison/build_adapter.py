#!/usr/bin/env python3
"""Build the local, reviewed method-comparison skill's ResearchOS read adapter.

This is a format projection for this bundled example, not an arbitrary-skill
installer or safety classifier. It reads one fixed source and executes none of it.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "researchos-method-comparison" / "SKILL.md"
TARGET = HERE / "skill-adapter.md"


def render(source: bytes) -> str:
    text = source.decode("utf-8")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ValueError("Expected a SKILL.md frontmatter block")
    body = text.split("\n---\n", 1)[1].strip()
    if not body:
        raise ValueError("The skill has no method instructions")
    digest = hashlib.sha256(source).hexdigest()
    return f'''---
type: generated_skill_adapter
title: "Method comparison skill adapter"
status: ready
sensitivity: public
source_sha256: "{digest}"
---

<!-- Generated by build_adapter.py. Edit the source skill, then regenerate. -->

# ResearchOS method adapter

## Agent Summary

This read-plan entry projects the reviewed [source skill](researchos-method-comparison/SKILL.md)
into ResearchOS Markdown. First run `python3 docs/plugins/method-comparison/build_adapter.py --check`
from the repository root. If it fails, stop this extension's execution and review or regenerate
the adapter; do not present a stale method as current. Use the source hash above in the result
receipt, alongside the extension ID and version supplied by the plan. The check establishes
file consistency, not scientific correctness or authorization to disclose task sources.

The method below runs within the host's current source scope, tools and result mode.
It adds no read permission or write authority. The public label applies to this reviewed
method text, not to the papers or results that a user later supplies.

{body}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if SOURCE.is_symlink() or SOURCE.parent.is_symlink() or TARGET.is_symlink():
        parser.exit(1, "Refusing symlinked example source or output.\n")
    expected = render(SOURCE.read_bytes())
    if args.write:
        TARGET.write_text(expected, encoding="utf-8")
        print("Rebuilt skill-adapter.md; review changes before upgrading the plugin.")
        return 0
    if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != expected:
        parser.exit(1, "Skill adapter is missing or stale; review the source and rebuild it.\n")
    print("Skill adapter matches its source; no method execution was performed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
